import { createToken } from '@avijs/core';
import { createReadStream } from 'node:fs';
import { mkdir, rm, stat, writeFile } from 'node:fs/promises';
import path from 'node:path';
import type { Readable } from 'node:stream';

/**
 * Where uploaded files live. The CMS ships a local-disk driver; an S3-compatible one only needs
 * these three methods (PutObject, DeleteObject, GetObject) and a different factory in MediaModule.
 */
export interface FileStorage {
  put(key: string, data: Buffer, contentType: string): Promise<void>;
  remove(key: string): Promise<void>;
  /** The file's bytes, or undefined when it does not exist. */
  open(key: string): Promise<{ stream: Readable; size: number } | undefined>;
}
export const FileStorage = createToken<FileStorage>('FileStorage');

/** Keys are generated by the media service: 32 hex characters and an image extension. */
export const STORAGE_KEY = /^[a-f0-9]{32}\.(png|jpg|gif|webp)$/;

export async function createLocalStorage(root: string): Promise<FileStorage> {
  const dir = path.resolve(root);
  await mkdir(dir, { recursive: true });

  const resolve = (key: string) => {
    // Keys never come from the client unchecked, but refuse anything that is not one anyway.
    if (!STORAGE_KEY.test(key)) throw new Error(`Invalid storage key: ${key}`);
    return path.join(dir, key);
  };

  return {
    async put(key, data) {
      await writeFile(resolve(key), data, { flag: 'wx' });
    },
    async remove(key) {
      await rm(resolve(key), { force: true });
    },
    async open(key) {
      const file = resolve(key);
      try {
        const info = await stat(file);
        if (!info.isFile()) return undefined;
        return { stream: createReadStream(file), size: info.size };
      } catch (error) {
        if ((error as NodeJS.ErrnoException).code === 'ENOENT') return undefined;
        throw error;
      }
    },
  };
}
